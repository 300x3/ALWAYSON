#!/usr/bin/env python3
"""ALWAYS ON - facility scheduler for ao-sim-fabrication (README Section 10.2, SIM-12).

Sequences cell and kitchen work against the boned cell datums in
GAZEBO/sim/boning.yaml and the RL object catalogue in GAZEBO/sim/objects.yaml.

The scheduler reads:
  * boning.yaml   - cell datums (cell-arms, cell-conveyor, cell-massing)
  * objects.yaml  - RL objects (marked parts, stock items, task targets)
                   and actors (arm-cell-1, shuttle-1)

It assigns each object to the cell that matches its class and emits a
deterministic schedule: cell, task id, object class, home pose, and the
boned datum it is sequenced against. Re-running is idempotent.

Output is YAML to stdout; use --write to persist to
GAZEBO/sim/facility-schedule.yaml.

Rehearsal only: this schedules simulation work, not real machines.
"""

from __future__ import annotations

import argparse
import pathlib
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parents[2]
BONING = ROOT / "GAZEBO" / "sim" / "boning.yaml"
OBJECTS = ROOT / "GAZEBO" / "sim" / "objects.yaml"
SCHEDULE = ROOT / "GAZEBO" / "sim" / "facility-schedule.yaml"

# Map object class -> cell id that can service it.
CLASS_TO_CELL = {
    "marked_part": "cell-arms",
    "stock_item": "cell-conveyor",
    "task_target": "cell-massing",
}


def load(path: pathlib.Path) -> dict:
    return yaml.safe_load(path.read_text())


def build_schedule(boning: dict, objects: dict) -> list:
    """Return a list of scheduled task dicts, one per object, ordered by cell."""
    cells = {c["id"]: c for c in boning.get("cells", [])}
    groups = objects.get("groups", [])

    tasks: list[dict] = []
    for group in groups:
        for obj in group.get("objects", []):
            obj_class = obj.get("class", "")
            cell_id = CLASS_TO_CELL.get(obj_class)
            if cell_id is None:
                continue  # no cell can service this class
            cell = cells.get(cell_id)
            if cell is None:
                continue  # cell datum missing
            datum = cell.get("datum", {})
            tasks.append(
                {
                    "cell": cell_id,
                    "cell_name": cell.get("name", cell_id),
                    "task_id": obj["id"],
                    "object_label": obj.get("label", obj["id"]),
                    "object_class": obj_class,
                    "home_pose": obj.get("home_pose", []),
                    "datum_origin": datum.get("origin", []),
                    "datum_extent": datum.get("extent", []),
                    "datum_centroid": datum.get("centroid", []),
                }
            )

    # Deterministic order: by cell id, then task id.
    tasks.sort(key=lambda t: (t["cell"], t["task_id"]))
    return tasks


def render_yaml(tasks: list, cells: dict) -> str:
    lines = [
        "# ALWAYS ON - facility schedule for ao-sim-fabrication",
        "# Generated by scripts/simulation/facility-scheduler.py",
        "# Rehearsal only: schedules simulation work, not real machines.",
        f"# {len(tasks)} tasks across {len(cells)} cells",
        "schema_version: \"1.0\"",
        "schedule:",
    ]
    if not tasks:
        lines.append("  []")
        return "\n".join(lines) + "\n"
    for t in tasks:
        lines.append(f"  - cell: {t['cell']!r}")
        lines.append(f"      cell_name: {t['cell_name']!r}")
        lines.append(f"      task_id: {t['task_id']!r}")
        lines.append(f"      object_label: {t['object_label']!r}")
        lines.append(f"      object_class: {t['object_class']!r}")
        lines.append(f"      home_pose: {t['home_pose']}")
        lines.append(f"      datum_origin: {t['datum_origin']}")
        lines.append(f"      datum_extent: {t['datum_extent']}")
        lines.append(f"      datum_centroid: {t['datum_centroid']}")
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(
        description="Facility scheduler for ao-sim-fabrication (SIM-12)"
    )
    ap.add_argument(
        "--write",
        action="store_true",
        help="persist schedule to GAZEBO/sim/facility-schedule.yaml",
    )
    args = ap.parse_args()

    boning = load(BONING)
    objects = load(OBJECTS)

    cells = {c["id"]: c for c in boning.get("cells", [])}
    tasks = build_schedule(boning, objects)

    output = render_yaml(tasks, cells)

    if args.write:
        SCHEDULE.write_text(output)
        print(
            f"wrote {len(tasks)} scheduled tasks across "
            f"{len({t['cell'] for t in tasks})} cells to {SCHEDULE}"
        )
        return 0

    print(output, end="")
    return 0


if __name__ == "__main__":
    sys.exit(main())